    private void configurarAgenda() {
        cmbOdontologos.removeAllItems();
        cmbConsultorios.removeAllItems();
        cmbOdontologos.addItem("Todos");
        cmbConsultorios.addItem("Todos");
        try {
            CitaControladora control = new CitaControladora();
            for (String item : control.odontologosActivos()) {
                cmbOdontologos.addItem(item);
            }
            for (String item : control.consultoriosActivos()) {
                cmbConsultorios.addItem(item);
            }
        } catch (PersistenciaException error) {
            JOptionPane.showMessageDialog(this, error.getMessage(), "No se cargaron los filtros", JOptionPane.ERROR_MESSAGE);
        }
        txtDianterior.addActionListener(e -> {
            fecha = fecha.minusDays(1);
            cargarAgenda();
        });
        btnDia_siguiente.addActionListener(e -> {
            if (fecha.isBefore(LocalDate.now())) {
                fecha = fecha.plusDays(1);
                cargarAgenda();
            }
            fecha = fecha.plusDays(1);
            cargarAgenda();
        });
        cmbOdontologos.addActionListener(e -> cargarAgenda());
        cmbConsultorios.addActionListener(e -> cargarAgenda());
        cargarAgenda();
    }

    private long idFiltro(javax.swing.JComboBox<String> combo) {
        Object item = combo.getSelectedItem();
        if (item == null || "Todos".equals(item.toString())) {
            return 0;
        }
        return Long.parseLong(item.toString().substring(0, item.toString().indexOf(" - ")));
    }

    private void cargarAgenda() {
        txtDía.setText(fecha.format(DateTimeFormatter.ofPattern("dd/MM/yyyy")));
        DefaultTableModel modelo = new DefaultTableModel(
                new Object[]{"ID", "Hora", "Paciente", "Odontólogo", "Consultorio", "Tipo", "Estado"}, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        tableCitas.setModel(modelo);
        try {
            ArrayList<Cita> citas = new CitaControladora().listarDia(fecha, idFiltro(cmbOdontologos), idFiltro(cmbConsultorios));
            DateTimeFormatter hora = DateTimeFormatter.ofPattern("HH:mm");
            for (Cita cita : citas) {
                modelo.addRow(new Object[]{cita.getIdCita(), cita.getInicio().format(hora),
                    cita.getPaciente(), cita.getOdontologo(), cita.getConsultorio(), cita.getTipo(), cita.getEstado()});
            }
            tableCitas.getColumnModel().getColumn(0).setMinWidth(0);
            tableCitas.getColumnModel().getColumn(0).setMaxWidth(0);
            tableCitas.getColumnModel().getColumn(0).setWidth(0);
            btnDia_siguiente.setEnabled(fecha.isBefore(LocalDate.now()));
            btnDia_siguiente.setEnabled(true);
        } catch (PersistenciaException | RuntimeException error) {
            JOptionPane.showMessageDialog(this, error.getMessage(), "No se pudo cargar la agenda", JOptionPane.ERROR_MESSAGE);
        }
    }

