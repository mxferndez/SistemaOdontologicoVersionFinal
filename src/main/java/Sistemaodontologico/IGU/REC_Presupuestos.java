    private void cargarPlanes() {
        DefaultTableModel modelo = new DefaultTableModel(new Object[]{"ID", "Documento", "Paciente", "Odontólogo", "Sesiones", "Total"}, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        jTable1.setModel(modelo);
        try {
            Object seleccion = jComboBox1.getSelectedItem();
            String filtro = seleccion == null ? "Todos los odontólogos" : seleccion.toString();
            for (PlanTratamiento plan : new PlanTratamientoControladora().listarPendientes()) {
                if (!"Todos los odontólogos".equals(filtro)
                        && !filtro.equals(plan.getIdOdontologo() + " - " + plan.getOdontologo())) {
                    continue;
                }
                modelo.addRow(new Object[]{plan.getIdPlan(), plan.getDocumento(), plan.getPaciente(),
                    plan.getOdontologo(), plan.getSesionesEstimadas(), plan.getTotal()});
            }
            jTable1.getColumnModel().getColumn(0).setMinWidth(0);
            jTable1.getColumnModel().getColumn(0).setMaxWidth(0);
            jTable1.getColumnModel().getColumn(0).setWidth(0);
        } catch (PersistenciaException | RuntimeException error) {
            JOptionPane.showMessageDialog(this, error.getMessage(), "No se pudieron cargar las propuestas", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void responder(boolean aceptar) {
        try {
            int fila = jTable1.getSelectedRow();
            if (fila < 0) {
                throw new IllegalArgumentException("Seleccione un plan de tratamiento.");
            }
            int modelo = jTable1.convertRowIndexToModel(fila);
            long idPlan = ((Number) jTable1.getModel().getValueAt(modelo, 0)).longValue();
            String decision = aceptar ? "aceptar" : "rechazar";
            int confirmar = JOptionPane.showConfirmDialog(this, "¿Desea " + decision + " esta propuesta?",
                    "Respuesta al plan", JOptionPane.YES_NO_OPTION);
            if (confirmar != JOptionPane.YES_OPTION) {
                return;
            }
            new PlanTratamientoControladora().responder(idPlan, aceptar);
            JOptionPane.showMessageDialog(this, aceptar ? "Plan aceptado y cuotas generadas." : "Plan rechazado.",
                    "Propuesta", JOptionPane.INFORMATION_MESSAGE);
            cargarPlanes();
        } catch (PersistenciaException | RuntimeException error) {
            JOptionPane.showMessageDialog(this, error.getMessage(), "No se pudo responder el plan", JOptionPane.ERROR_MESSAGE);
        }
    }

